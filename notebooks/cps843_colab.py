class WordSequenceDataset(Dataset):

    def __init__(
        self,
        base_dir: str,
        split: str = "train",  # "train" or "val"
        target_height: int = TARGET_HEIGHT,
        transform=None,
    ):

        self.base_dir = base_dir
        self.split = split
        self.target_height = target_height
        self.transform = transform

        # Create character to index mapping (for CTC, blank is typically last)
        self.char_to_idx = {char: idx for idx, char in enumerate(LABELS)}
        self.idx_to_char = {idx: char for char, idx in self.char_to_idx.items()}
        self.num_classes = len(LABELS) + 1  # +1 for CTC blank token
        self.blank_idx = len(LABELS)  # Blank token index

        # Load all images and labels
        self.image_paths = []
        self.labels = []
        self._load_images()

        print(f"Loaded {len(self.image_paths)} images for {split} split")
        print(f"Number of character classes: {len(LABELS)} (+ 1 blank = {self.num_classes})")

        # Show some example labels
        if len(self.labels) > 0:
            print("Sample labels:")
            for i in range(min(5, len(self.labels))):
                label_str = ''.join([self.idx_to_char[idx] for idx in self.labels[i]])
                print(f"  {label_str}")

    def _load_images(self):
        """Load all images from the folder structure."""
        split_dir = os.path.join(self.base_dir, f"word_{self.split}")

        if not os.path.exists(split_dir):
            raise ValueError(f"Directory {split_dir} does not exist")

        # Get all PNG files
        image_files = [f for f in os.listdir(split_dir)
                      if f.lower().endswith('.png')]

        for img_file in sorted(image_files):
            img_path = os.path.join(split_dir, img_file)

            # Extract label from filename: {word}_{number}.png -> {word}
            # Split by underscore and take everything except the last part (number)
            name_without_ext = os.path.splitext(img_file)[0]
            parts = name_without_ext.split('_')

            if len(parts) < 2:
                print(f"Warning: Could not parse label from filename {img_file}, skipping...")
                continue

            # Join all parts except the last one (which is the number)
            word = '_'.join(parts[:-1])

            # Encode word as sequence of character indices
            label_seq = []
            for char in word:
                if char in self.char_to_idx:
                    label_seq.append(self.char_to_idx[char])
                else:
                    # Skip characters not in our label set
                    print(f"Warning: Character '{char}' not in LABELS, skipping from word '{word}'")

            if len(label_seq) == 0:
                print(f"Warning: No valid characters in word '{word}', skipping...")
                continue

            self.image_paths.append(img_path)
            self.labels.append(label_seq)

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        """
        returns:            image: Tensor of shape (1, H, W) - grayscale word image (variable width)
            label: List of character indices (ground truth sequence)
            label_length: Length of the label sequence
        """
