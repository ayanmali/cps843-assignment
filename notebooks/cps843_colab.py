# Custom collate function for batching the data
def collate_fn(batch):

    images, labels, label_lengths = zip(*batch)

    # Get maximum width for padding
    max_width = max(img.shape[2] for img in images)

    # Pad images to same width
    padded_images = []
    image_widths = []
    for img in images:
        _, h, w = img.shape
        image_widths.append(w)
        # Pad right side with zeros
        padding = max_width - w
        padded_img = torch.nn.functional.pad(img, (0, padding), mode='constant', value=0)
        padded_images.append(padded_img)

    # Stack images
    images_tensor = torch.stack(padded_images)

    # Concatenate all labels
    labels_tensor = torch.cat(labels)

    # Convert to tensors
    label_lengths_tensor = torch.tensor(label_lengths, dtype=torch.long)
    image_widths_tensor = torch.tensor(image_widths, dtype=torch.long)

    return images_tensor, labels_tensor, label_lengths_tensor, image_widths_tensor


def calculate_input_lengths(image_widths: torch.Tensor) -> torch.Tensor:

    return (image_widths // 4).long()


def train_epoch(model, dataloader, criterion, optimizer, device):
    #Train for one epoch
    model.train()
    running_loss = 0.0
    total_samples = 0

    for images, labels, label_lengths, image_widths in tqdm(dataloader, desc="Training"):
        images = images.to(device)
        labels = labels.to(device)
        label_lengths = label_lengths.to(device)
        image_widths = image_widths.to(device)

        # Calculate input lengths (sequence length from CNN output)
        input_lengths = calculate_input_lengths(image_widths)
        input_lengths = input_lengths.to(device)

        # Forward pass
        optimizer.zero_grad()
        logits = model(images)  # Shape: (W, B, num_classes)

        # CTC loss expects log_probs in shape (T, N, C) where:
        # T = sequence length, N = batch size, C = num classes
        log_probs = nn.functional.log_softmax(logits, dim=2)

        # Calculate loss
        loss = criterion(log_probs, labels, input_lengths, label_lengths)

        # Backward pass
        loss.backward()
        optimizer.step()

        # Stastatstistics
        running_loss += loss.item()
        total_samples += images.size(0)

    epoch_loss = running_loss / len(dataloader)
    return epoch_loss


def calculate_edit_distance(s1: str, s2: str) -> int:
    # Levenshtein distance
    m, n = len(s1), len(s2)

    # Create a matrix to store distances
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    # Initialize base cases
    for i in range(m + 1):
        dp[i][0] = i
    for j in range(n + 1):
        dp[0][j] = j

    # Fill the matrix
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if s1[i - 1] == s2[j - 1]:
                dp[i][j] = dp[i - 1][j - 1]
            else:
                dp[i][j] = min(
                    dp[i - 1][j] + 1,      # deletion
                    dp[i][j - 1] + 1,      # insertion
                    dp[i - 1][j - 1] + 1   # substitution
                )

    return dp[m][n]


def calculate_cer(predicted: str, reference: str) -> float:

    # CER = Edit Distance / Length of Reference

    if len(reference) == 0:
        return 1.0 if len(predicted) > 0 else 0.0

    edit_dist = calculate_edit_distance(predicted, reference)
    return edit_dist / len(reference)


def validate(model, dataloader, criterion, device, idx_to_char):
    # validate model w/ CER
    model.eval()
    running_loss = 0.0
    total_samples = 0
    total_cer = 0.0
    total_chars = 0

    with torch.no_grad():
        for images, labels, label_lengths, image_widths in tqdm(dataloader, desc="Validating"):
            images = images.to(device)
            labels = labels.to(device)
            label_lengths = label_lengths.to(device)
            image_widths = image_widths.to(device)

            # Calculate input lengths
            input_lengths = calculate_input_lengths(image_widths)
            input_lengths = input_lengths.to(device)

            # Forward pass
            logits = model(images)
            log_probs = nn.functional.log_softmax(logits, dim=2)

            # Calculate loss
            loss = criterion(log_probs, labels, input_lengths, label_lengths)

            running_loss += loss.item()
            total_samples += images.size(0)

            # Decode predictions for CER calculation
            # Use greedy decoding (argmax at each timestep)
            predictions = log_probs.argmax(dim=2)  # Shape: (W, B)
            predictions = predictions.permute(1, 0)  # Shape: (B, W)

            # Decode predictions (remove blanks and consecutive duplicates)
            batch_size = predictions.size(0)
            for i in range(batch_size):
                pred_seq = predictions[i].cpu().numpy()
                # Remove blanks and consecutive duplicates
                decoded = []
                prev = None
                for idx in pred_seq:
                    if idx != len(LABELS) and idx != prev:  # Not blank and not duplicate
                        decoded.append(idx_to_char[idx])
                    prev = idx
                pred_str = ''.join(decoded)

                # Get ground truth
                start_idx = sum(label_lengths[:i].cpu().numpy())
                end_idx = start_idx + label_lengths[i].cpu().item()
                gt_seq = labels[start_idx:end_idx].cpu().numpy()
                gt_str = ''.join([idx_to_char[idx] for idx in gt_seq])

                # Calculate CER for this prediction
                cer = calculate_cer(pred_str, gt_str)
                total_cer += cer * len(gt_str)  # Weight by reference length
                total_chars += len(gt_str)

    epoch_loss = running_loss / len(dataloader)
    avg_cer = total_cer / total_chars if total_chars > 0 else 1.0
    char_accuracy = (1.0 - avg_cer) * 100.0  # Convert to percentage

    return epoch_loss, avg_cer, char_accuracy


